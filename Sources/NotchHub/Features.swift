struct ClipImage: Identifiable {
    let id = UUID()
    let thumbnail: NSImage
    let data: Data
    let type: NSPasteboard.PasteboardType
}

@MainActor
final class ClipboardStore: ObservableObject {
    enum Kind { case text, image }

    @Published private(set) var items: [String] = []
    @Published private(set) var images: [ClipImage] = []
    @Published private(set) var lastAddedKind: Kind = .text

    private let maxItems = 10
    // Full-resolution screenshots can be several MB each, so image history is kept shorter.
    private let maxImages = 8
    // Types password managers set to mark secrets that clipboard tools should not record.
    private let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    init() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: skippedTypes) else { return }

        // Text wins: rich-text copies (Word, Excel, browsers) often carry an image rendering alongside the text.
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            items.removeAll { $0 == text }
            items.insert(text, at: 0)
            if items.count > maxItems { items.removeLast(items.count - maxItems) }
            lastAddedKind = .text
            return
        }

        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            guard let data = pasteboard.data(forType: type) else { continue }
            if let existing = images.firstIndex(where: { $0.data == data }) {
                images.insert(images.remove(at: existing), at: 0)
            } else if let thumbnail = Self.thumbnail(of: data) {
                images.insert(ClipImage(thumbnail: thumbnail, data: data, type: type), at: 0)
                if images.count > maxImages { images.removeLast(images.count - maxImages) }
            } else {
                continue
            }
            lastAddedKind = .image
            return
        }
    }

    // Decoding a small thumbnail keeps the panel light no matter how large the screenshot is.
    private static func thumbnail(of data: Data) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, [
                  kCGImageSourceCreateThumbnailFromImageAlways: true,
                  kCGImageSourceCreateThumbnailWithTransform: true,
                  kCGImageSourceThumbnailMaxPixelSize: 320,
              ] as CFDictionary)
        else { return nil }
        return NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
    }

    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    func copy(_ image: ClipImage) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setData(image.data, forType: image.type)
    }

    func clearText() {
        items.removeAll()
    }

    func clearImages() {
        images.removeAll()
    }
}

@MainActor
final class MusicController: ObservableObject {
    @Published private(set) var player: String?
    @Published private(set) var title = ""
    @Published private(set) var artist = ""
    @Published private(set) var isPlaying = false
    @Published private(set) var artwork: NSImage?
    @Published private(set) var artworkGlow: Color?
    @Published private(set) var duration: Double = 0
    @Published private(set) var position: Double = 0
    @Published private(set) var positionDate = Date()

    private struct Player {
        let name: String
        let bundleID: String
        let durationSeconds: String
    }

    private let players = [
        Player(name: "Spotify", bundleID: "com.spotify.client", durationSeconds: "(duration of current track) / 1000"),
        Player(name: "Music", bundleID: "com.apple.Music", durationSeconds: "duration of current track"),
    ]
    private var trackKey: String?
    private var timer: Timer?
    private var pendingPoll: DispatchWorkItem?

    init() {
        poll()

        // Spotify and Music broadcast these on every play/pause/track change, so no frequent polling is needed.
        let center = DistributedNotificationCenter.default()
        for name in ["com.spotify.client.PlaybackStateChanged", "com.apple.Music.playerInfo"] {
            center.addObserver(forName: Notification.Name(name), object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.schedulePoll() }
            }
        }
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didTerminateApplicationNotification, object: nil, queue: .main
        ) { [weak self] _ in
            MainActor.assumeIsolated { self?.schedulePoll() }
        }

        // Slow fallback to correct drift, e.g. after seeking inside the player.
        timer = Timer.scheduledTimer(withTimeInterval: 15, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func schedulePoll() {
        pendingPoll?.cancel()
        let work = DispatchWorkItem { [weak self] in
            MainActor.assumeIsolated { self?.poll() }
        }
        pendingPoll = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15, execute: work)
    }

    func currentPosition(at date: Date) -> Double {
        let elapsed = isPlaying ? date.timeIntervalSince(positionDate) : 0
        return min(duration, position + elapsed)
    }

    func poll() {
        var paused: (String, [String])?
        // Only query running apps, since `tell application` would launch a closed one.
        for p in players where !NSRunningApplication.runningApplications(withBundleIdentifier: p.bundleID).isEmpty {
            guard let output = AppleScript.run("""
            tell application "\(p.name)"
                if player state is stopped then return "stopped"
                return (player state as string) & linefeed & (name of current track) & linefeed & (artist of current track) & linefeed & (player position as string) & linefeed & ((\(p.durationSeconds)) as string)
            end tell
            """) else { continue }

            let parts = output.components(separatedBy: "\n")
            guard parts.count == 5 else { continue }
            if parts[0] == "playing" {
                apply(p.name, parts)
                return
            }
            if paused == nil { paused = (p.name, parts) }
        }

        if let (name, parts) = paused {
            apply(name, parts)
        } else if player != nil {
            player = nil
            isPlaying = false
            artwork = nil
            artworkGlow = nil
            trackKey = nil
        }
    }

    // Assigning only on change avoids re-rendering the panel for identical values.
    private func apply(_ name: String, _ parts: [String]) {
        let playing = parts[0] == "playing"
        if player != name { player = name }
        if isPlaying != playing { isPlaying = playing }
        if title != parts[1] { title = parts[1] }
        if artist != parts[2] { artist = parts[2] }
        let newDuration = Self.number(parts[4])
        if duration != newDuration { duration = newDuration }
        position = Self.number(parts[3])
        positionDate = Date()

        let key = "\(name)|\(title)|\(artist)"
        if key != trackKey {
            trackKey = key
            loadArtwork(player: name, key: key)
        }
    }

    private func setArtwork(_ image: NSImage?) {
        artwork = image
        artworkGlow = image.flatMap(Self.averageColor).map(Color.init(nsColor:))
    }

    private static func averageColor(of image: NSImage) -> NSColor? {
        guard let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return nil }
        let input = CIImage(cgImage: cg)
        guard let output = CIFilter(name: "CIAreaAverage", parameters: [
            kCIInputImageKey: input,
            kCIInputExtentKey: CIVector(cgRect: input.extent),
        ])?.outputImage else { return nil }
        var pixel = [UInt8](repeating: 0, count: 4)
        CIContext(options: [.workingColorSpace: NSNull()]).render(
            output, toBitmap: &pixel, rowBytes: 4,
            bounds: CGRect(x: 0, y: 0, width: 1, height: 1),
            format: .RGBA8, colorSpace: nil
        )
        return NSColor(red: CGFloat(pixel[0]) / 255, green: CGFloat(pixel[1]) / 255, blue: CGFloat(pixel[2]) / 255, alpha: 1)
    }

    // AppleScript formats reals with the locale's decimal separator.
    private static func number(_ text: String) -> Double {
        Double(text.replacingOccurrences(of: ",", with: ".")) ?? 0
    }

    private func loadArtwork(player: String, key: String) {
        if player == "Spotify" {
            guard let urlString = AppleScript.run("tell application \"Spotify\" to return artwork url of current track"),
                  let url = URL(string: urlString)
            else { return setArtwork(nil) }
            Task { [weak self] in
                guard let (data, _) = try? await URLSession.shared.data(from: url),
                      let image = NSImage(data: data),
                      let self, self.trackKey == key
                else { return }
                self.setArtwork(image)
            }
        } else {
            let data = AppleScript.descriptor("tell application \"Music\" to return raw data of artwork 1 of current track")?.data
            setArtwork(data.flatMap(NSImage.init(data:)))
        }
    }

    func playPause() {
        // Flip immediately so the button responds before the player confirms.
        if player != nil { isPlaying.toggle() }
        send("playpause")
    }
    func next() { send("next track") }
    func previous() { send("previous track") }

    private func send(_ command: String) {
        guard let player else { return }
        AppleScript.run("tell application \"\(player)\" to \(command)")
        schedulePoll()
    }
}
