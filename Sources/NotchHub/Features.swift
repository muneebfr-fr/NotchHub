struct QuickLink: Identifiable, Decodable {
    let name: String
    let url: URL
    /// An SF Symbols name, e.g. "graduationcap.fill".
    let symbol: String
    var id: String { name }
}

enum QuickLinks {
    /// Personal links live outside the repo so they aren't shared with the code.
    static let configURL = FileManager.default.homeDirectoryForCurrentUser
        .appendingPathComponent("Library/Application Support/NotchHub/links.json")

    static let all: [QuickLink] = {
        guard let data = try? Data(contentsOf: configURL),
              let links = try? JSONDecoder().decode([QuickLink].self, from: data)
        else { return examples }
        return links
    }()

    private static let examples: [QuickLink] = [
        QuickLink(name: "Google", url: URL(string: "https://www.google.com")!, symbol: "magnifyingglass"),
        QuickLink(name: "GitHub", url: URL(string: "https://github.com")!, symbol: "chevron.left.forwardslash.chevron.right"),
    ]
}

@MainActor
enum AppleScript {
    // Compiling is the slow part of NSAppleScript, so each source is compiled once.
    private static var compiled: [String: NSAppleScript] = [:]

    @discardableResult
    static func run(_ source: String) -> String? {
        descriptor(source)?.stringValue
    }

    static func descriptor(_ source: String) -> NSAppleEventDescriptor? {
        let script: NSAppleScript
        if let cached = compiled[source] {
            script = cached
        } else {
            guard let fresh = NSAppleScript(source: source) else { return nil }
            fresh.compileAndReturnError(nil)
            compiled[source] = fresh
            script = fresh
        }
        var error: NSDictionary?
        let result = script.executeAndReturnError(&error)
        return error == nil ? result : nil
    }
}

